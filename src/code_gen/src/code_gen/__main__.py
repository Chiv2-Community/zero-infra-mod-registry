"""Generate dataclasses from the public schemas; never edit generated output."""
from __future__ import annotations

import argparse
from pathlib import Path
import json
from typing import cast

from datamodel_code_generator import InputFileType, PythonVersion, generate
from datamodel_code_generator.enums import DataModelType, DefaultValueType
from datamodel_code_generator.format import DatetimeClassType, Formatter

from mod_registry_core.json_types import JsonObject, JsonValue, decode_json, json_object, json_string

ROOT = Path.cwd()
OUTPUT = ROOT / "src/generated_models/src/generated_models"


def render(filenames: tuple[str, ...], *, dependency: bool = False, overrides: dict[str, str] | None = None) -> str:
    # Inline local references so generation never fetches a schema over the network.
    definitions: JsonObject = {}
    documents = {path.name: json_object(decode_json(path.read_text())) for path in (ROOT / "schemas").glob("*.schema.json")}

    def inline(value: JsonValue, filename: str) -> JsonValue:
        if isinstance(value, list):
            return [inline(item, filename) for item in value]
        if not isinstance(value, dict):
            return value
        result: JsonObject = {
            key: inline(item, filename) for key, item in value.items()
            if key != "x-python-datetime" and not (key in {"$id", "$schema"} and isinstance(item, str))
        }
        if value.get("x-python-datetime"):
            # ISO timestamps in existing registries may be timezone-naive. This
            # generation-only hint chooses datetime without narrowing validation.
            result["format"] = "date-time"
        if "$ref" in value:
            target, _, pointer = json_string(value["$ref"]).partition("#")
            target = target.rsplit("/", 1)[-1] if target else filename
            name = pointer.rsplit("/", 1)[-1] if pointer else "root"
            key = target.removesuffix(".schema.json").replace("-", "_") + "_" + name
            result["$ref"] = f"#/$defs/{key}"
            if key not in definitions:
                definitions[key] = {}  # Break recursive references.
                document = documents[target]
                if pointer:
                    for part in pointer.lstrip("/").split("/"):
                        document = json_object(document[part])
                definitions[key] = inline(document, target)
        return result

    for filename in filenames:
        for name, definition in json_object(documents[filename]["$defs"]).items():
            if dependency and name != "dependency":
                continue
            key = filename.removesuffix(".schema.json").replace("-", "_") + "_" + name
            definitions[key] = inline(definition, filename)
    bundle: JsonObject = {"type": "object", "$defs": definitions}
    result = generate(
        json.dumps(bundle), input_file_type=InputFileType.JsonSchema,
        output_model_type=DataModelType.DataclassesDataclass,
        target_python_version=PythonVersion.PY_312, frozen_dataclasses=True,
        use_standard_collections=True, use_union_operator=True, collapse_root_models=True,
        type_overrides=overrides, use_title_as_name=True, disable_timestamp=True,
        apply_default_values_for_required_fields=True, strict_nullable=True,
        output_datetime_class=DatetimeClassType.Datetime, use_subclass_enum=True,
        capitalise_enum_members=True, deserialize_default_values=[DefaultValueType.Enum],
        formatters=[Formatter.BLACK, Formatter.ISORT],
        custom_file_header="# Generated by python -m code_gen. DO NOT EDIT.",
    )
    if not isinstance(result, str):
        raise RuntimeError("Expected a single generated module")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        OUTPUT / "metadata.py": render(
            ("mod-metadata.schema.json", "dll-metadata.schema.json", "pak-manifest.schema.json"),
            overrides={name: "generated_models.dependencies.Dependency"
                       for name in ("Dependency", "CommonDependency", "CommonPluginDependency")}),
        OUTPUT / "requests.py": render(("request.schema.json",)),
        OUTPUT / "dependencies.py": render(("mod-metadata.schema.json",), dependency=True),
    }
    for path, generated in outputs.items():
        if cast(bool, args.check):
            if not path.exists() or path.read_text() != generated:
                raise SystemExit("Generated models are stale. Run uv run python -m code_gen")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(generated)


if __name__ == "__main__":
    main()
