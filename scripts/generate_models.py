"""Generate dataclasses from the public schemas; never edit generated output."""
from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys
import tempfile
import json

from mod_registry_core.json_types import JsonObject, JsonValue, decode_json, json_object, json_string

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/zero_infra_mod_registry/models/generated.py"
REQUEST_OUTPUT = ROOT / "src/core/src/mod_registry_core/generated_requests.py"
REQUEST_SCHEMA = REQUEST_OUTPUT.parent / "schemas/request.schema.json"


def generate(request: bool = False) -> str:
    # Inline local references so generation never fetches a schema over the network.
    definitions: JsonObject = {}
    documents = {path.name: json_object(decode_json(path.read_text())) for path in (ROOT / "schemas").glob("*.schema.json")}

    def inline(value: JsonValue, filename: str) -> JsonValue:
        if isinstance(value, list):
            return [inline(item, filename) for item in value]
        if not isinstance(value, dict):
            return value
        result: JsonObject = {
            key: inline(item, filename) for key, item in value.items()
            if key != "x-python-datetime" and not (key in {"$id", "$schema"} and isinstance(item, str))
        }
        if value.get("x-python-datetime"):
            # ISO timestamps in existing registries may be timezone-naive. This
            # generation-only hint chooses datetime without narrowing validation.
            result["format"] = "date-time"
        if "$ref" in value:
            target, _, pointer = json_string(value["$ref"]).partition("#")
            target = target.rsplit("/", 1)[-1] if target else filename
            name = pointer.rsplit("/", 1)[-1] if pointer else "root"
            key = target.removesuffix(".schema.json").replace("-", "_") + "_" + name
            result["$ref"] = f"#/$defs/{key}"
            if key not in definitions:
                definitions[key] = {}  # Break recursive references.
                document = documents[target]
                if pointer:
                    for part in pointer.lstrip("/").split("/"):
                        document = json_object(document[part])
                definitions[key] = inline(document, target)
        return result

    filenames = ("request.schema.json",) if request else ("mod-metadata.schema.json", "dll-metadata.schema.json", "pak-manifest.schema.json")
    for filename in filenames:
        for name, definition in json_object(documents[filename]["$defs"]).items():
            key = filename.removesuffix(".schema.json").replace("-", "_") + "_" + name
            definitions[key] = inline(definition, filename)
    with tempfile.TemporaryDirectory() as directory:
        schema = Path(directory) / "models.json"
        output = Path(directory) / "generated.py"
        bundle: JsonObject = {"type": "object", "$defs": definitions}
        schema.write_text(json.dumps(bundle))
        subprocess.run([
            sys.executable, "-m", "datamodel_code_generator", "--input", str(schema),
            "--input-file-type", "jsonschema", "--output", str(output),
            "--output-model-type", "dataclasses.dataclass", "--target-python-version", "3.12",
            "--frozen-dataclasses", "--use-standard-collections", "--use-union-operator",
            "--use-title-as-name", "--disable-timestamp", "--use-default", "--strict-nullable",
            "--output-datetime-class", "datetime", "--use-subclass-enum", "--capitalise-enum-members",
            "--deserialize-default-values", "enum",
            "--custom-template-dir", str(ROOT / "scripts/templates"),
            "--additional-imports", "mod_registry_core.json_types.JsonValue,mod_registry_core.json_types.JsonObject,typing.override",
            "--formatters", "black", "isort",
            "--custom-file-header", "# Generated by scripts/generate_models.py. DO NOT EDIT.",
        ], check=True, cwd=ROOT)
        return output.read_text()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.parse_args()
    outputs = {
        OUTPUT: generate(), REQUEST_OUTPUT: generate(True),
        REQUEST_SCHEMA: (ROOT / "schemas/request.schema.json").read_text(),
    }
    for path, generated in outputs.items():
        if "--check" in sys.argv[1:]:
            if not path.exists() or path.read_text() != generated:
                raise SystemExit("Generated models are stale. Run uv run python scripts/generate_models.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(generated)


if __name__ == "__main__":
    main()
